class I18nManager:
    _current_lang = 'ko'

    @classmethod
    def set_language(cls, lang: str):
        if lang in STRINGS:
            cls._current_lang = lang

    @classmethod
    def get_language(cls) -> str:
        return cls._current_lang

    @classmethod
    def get_supported_languages(cls) -> List[str]:
        return list(SUPPORTED_LANGUAGES)

    @classmethod
    def get_language_name(cls, lang: str) -> str:
        return LANG_NAMES.get(lang, lang)

    @classmethod
    def get_language_flag(cls, lang: str) -> str:
        return LANG_FLAGS.get(lang, '🌐')

    @classmethod
    def t(cls, key: str, **kwargs) -> str:
        lang_dict = STRINGS.get(cls._current_lang, STRINGS['ko'])
        template = lang_dict.get(key, STRINGS['ko'].get(key, key))
        if kwargs:
            try:
                return template.format(**kwargs)
            except Exception:
                return template
        return template
